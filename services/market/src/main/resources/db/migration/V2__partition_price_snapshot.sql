-- price_snapshot을 as_of(Asia/Seoul 날짜) 기준 RANGE 파티션 테이블로 바꾸고 응답 원문(raw)을 담는다.
-- 파티션 테이블의 유니크 제약은 파티션 키를 포함해야 하므로 event_id 단독 유니크는 (event_id, as_of)가 된다.
-- 기존 행은 새 테이블로 옮기고, 행이 있는 날짜마다 파티션을 만든다.

ALTER TABLE price_snapshot RENAME TO price_snapshot_legacy;
ALTER SEQUENCE price_snapshot_id_seq RENAME TO price_snapshot_legacy_id_seq;
ALTER TABLE price_snapshot_legacy RENAME CONSTRAINT price_snapshot_pkey TO price_snapshot_legacy_pkey;
ALTER TABLE price_snapshot_legacy RENAME CONSTRAINT price_snapshot_event_id_key TO price_snapshot_legacy_event_id_key;
ALTER INDEX idx_price_snapshot_symbol_as_of RENAME TO idx_price_snapshot_legacy_symbol_as_of;

CREATE TABLE price_snapshot (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    event_id    UUID        NOT NULL,
    symbol      VARCHAR(6)  NOT NULL,
    as_of       TIMESTAMPTZ NOT NULL,
    price       BIGINT      NOT NULL CHECK (price >= 0),
    raw         JSONB,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id, as_of),
    UNIQUE (event_id, as_of)
) PARTITION BY RANGE (as_of);

CREATE INDEX idx_price_snapshot_symbol_as_of ON price_snapshot (symbol, as_of DESC);

-- 파티션 이름과 경계는 서비스가 저장 직전에 만드는 규칙(price_snapshot_pYYYYMMDD, KST 자정)과 같다.
DO $$
DECLARE
    d date;
BEGIN
    FOR d IN SELECT DISTINCT (as_of AT TIME ZONE 'Asia/Seoul')::date FROM price_snapshot_legacy ORDER BY 1 LOOP
        EXECUTE format('CREATE TABLE %I PARTITION OF price_snapshot FOR VALUES FROM (%L) TO (%L)',
                       'price_snapshot_p' || to_char(d, 'YYYYMMDD'),
                       (d::timestamp AT TIME ZONE 'Asia/Seoul'),
                       ((d + 1)::timestamp AT TIME ZONE 'Asia/Seoul'));
    END LOOP;
END $$;

INSERT INTO price_snapshot (id, event_id, symbol, as_of, price, received_at)
SELECT id, event_id, symbol, as_of, price, received_at FROM price_snapshot_legacy;

SELECT setval(pg_get_serial_sequence('price_snapshot', 'id'),
              COALESCE((SELECT max(id) FROM price_snapshot_legacy), 0) + 1, false);

DROP TABLE price_snapshot_legacy;
